def ssc_chart(step_type, difficulty, meter, measures, timing=(), description=""):
    """One #NOTEDATA block in the layout StepMania 5 saves, with `timing`: tag lines of the
    chart's own timing."""
    lines = [
        "",
        f"//---------------{step_type} - {description}----------------",
        "#NOTEDATA:;",
        "#CHARTNAME:;",
        f"#STEPSTYPE:{step_type};",
        f"#DESCRIPTION:{description};",
        "#CHARTSTYLE:;",
        f"#DIFFICULTY:{difficulty};",
        f"#METER:{meter};",
        f"#RADARVALUES:{radar5};",
        "#CREDIT:;",
        *timing,
        "#NOTES:",
    ]
    for i, measure in enumerate(measures):
        if i:
            lines.append(",")
        lines.extend(measure)
    lines.append(";")
    return lines


def ssc_timing(bpms, stops, signatures="0.000000=4=4"):
    """Every timing tag StepMania 5 writes for a song or a chart with timing of its own."""
    return [
        "#OFFSET:-0.250000;",
        f"#BPMS:{bpms};",
        f"#STOPS:{stops};",
        "#DELAYS:;",
        "#WARPS:;",
        f"#TIMESIGNATURES:{signatures};",
        "#TICKCOUNTS:0.000000=4;",
        "#COMBOS:0.000000=1;",
        "#SPEEDS:0.000000=1.000000=0.000000=0;",
        "#SCROLLS:0.000000=1.000000;",
        "#FAKES:;",
        "#LABELS:0.000000=Song Start;",
    ]


