def chart(step_type, description, difficulty, meter, radar, measures):
    """One #NOTES block in the layout StepMania saves."""
    lines = [
        "",
        f"//---------------{step_type} - {description}----------------",
        "#NOTES:",
        f"     {step_type}:",
        f"     {description}:",
        f"     {difficulty}:",
        f"     {meter}:",
        f"     {radar}:",
    ]
    for i, measure in enumerate(measures):
        lines.append("// measure 0" if i == 0 else f",  // measure {i}")
        lines.extend(measure)
    lines.append(";")
    return lines


def subdivision_measure(rows):
    """A measure of `rows` rows with a tap on the left first and the right last."""
    return ["1000"] + ["0000"] * (rows - 2) + ["0001"]


