def stats_chart(difficulty, meter, description, measures):
    """A dance-single chart from a list of (comment, measure) pairs."""
    comments = [comment for comment, _ in measures]
    rows = [measure for _, measure in measures]
    return chart("dance-single", description, difficulty, meter, radar5, rows, comments)


