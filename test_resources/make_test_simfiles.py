def chart(step_type, description, difficulty, meter, radar, measures, comments=None):
    """One #NOTES block in the layout StepMania saves. `comments` has one per measure, written
    after its "// measure N"."""
    lines = [
        "",
        f"//---------------{step_type} - {description}----------------",
        "#NOTES:",
        f"     {step_type}:",
        f"     {description}:",
        f"     {difficulty}:",
        f"     {meter}:",
        f"     {radar}:",
    ]
    for i, measure in enumerate(measures):
        label = "// measure 0" if i == 0 else f",  // measure {i}"
        if comments:
            label += f": {comments[i]}"
        lines.append(label)
        lines.extend(measure)
    lines.append(";")
    return lines


def subdivision_measure(rows):
    """A measure of `rows` rows with a tap on the left first and the right last."""
    return ["1000"] + ["0000"] * (rows - 2) + ["0001"]


def sparse(rows, notes):
    """A measure of `rows` rows, empty except for the ones in `notes`, a dict of row index -> row."""
    return [notes.get(r, "0000") for r in range(rows)]


def taps(rows, positions):
    """A measure of `rows` rows with a tap on each row in `positions`, cycling left, down, up, right."""
    arrows = ["1000", "0100", "0010", "0001"]
    return sparse(rows, {r: arrows[i % 4] for i, r in enumerate(positions)})


