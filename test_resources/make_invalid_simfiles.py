"""Writes the invalid .sm test files for ddr-trainer's loader into invalid/ next to this script.

Run it with `python3 test_resources/make_invalid_simfiles.py` after changing it. Each file is
VALID with one thing broken. A new case also needs an entry in INVALID_FILES in
src/sim_loader.rs, saying which error it must fail with.
"""
import pathlib

out = pathlib.Path(__file__).resolve().parent / "invalid"

GENERATED = "// Generated by test_resources/make_invalid_simfiles.py, so edit that instead of this.\n"

VALID = """#TITLE:{title};
#MUSIC:{title}.ogg;
#OFFSET:0.000;
#BPMS:0.000=120.000;
#STOPS:;
#NOTES:
     dance-single:
     :
     Hard:
     8:
     :
1000
0100
0010
0001
,
0000
0000
0000
0000
;
"""

# file name -> (what's wrong, text to replace in VALID, replacement)
CASES = {
    "bad_offset.sm": ("#OFFSET is not a number.", "#OFFSET:0.000;", "#OFFSET:abc;"),
    "bpm_without_equals.sm": (
        "The second #BPMS entry has no '=bpm'.",
        "#BPMS:0.000=120.000;",
        "#BPMS:0.000=120.000,64.000;",
    ),
    "bad_stop_length.sm": ("The stop's length is not a number.", "#STOPS:;", "#STOPS:16.000=long;"),
    "missing_bpms.sm": ("There is no #BPMS tag.", "#BPMS:0.000=120.000;\n", ""),
    "unterminated_tag.sm": ("The chart is missing its closing ';'.", "0000\n;\n", "0000\n"),
    "too_few_chart_fields.sm": (
        "The chart header is missing its groove radar line, so #NOTES has 5 fields instead of 6.",
        "     8:\n     :\n",
        "     8:\n",
    ),
    "unknown_difficulty.sm": ("The chart's difficulty is not one StepMania uses.", "     Hard:", "     Impossible:"),
    "bad_meter.sm": ("The chart's meter (rating) is not a number.", "     8:", "     eight:"),
    "unsupported_note.sm": (
        "Measure 1 has a lift (L), which Note has no variant for.",
        ",\n0000\n",
        ",\n0L00\n",
    ),
    "wrong_row_width.sm": ("Measure 0 has a 5-column row in a dance-single chart.", "1000\n0100", "10000\n0100"),
}

out.mkdir(parents=True, exist_ok=True)
for name, (problem, old, new) in CASES.items():
    title = name.removesuffix(".sm")
    valid = VALID.format(title=title)
    assert valid.count(old) == 1, name
    text = f"// Invalid test simfile for ddr-trainer's loader. {problem}\n" + GENERATED + valid.replace(old, new)
    (out / name).write_text(text, encoding="utf-8")

# Saved as Shift-JIS, which some older simfiles use, instead of UTF-8.
text = "// Invalid test simfile for ddr-trainer's loader. It is Shift-JIS, not UTF-8.\n" + GENERATED
(out / "not_utf8.sm").write_bytes((text + VALID.format(title="テスト")).encode("shift_jis"))

# A song folder whose .sm file doesn't share the folder's name, so loading the folder finds nothing.
folder = out / "Mismatched Folder"
folder.mkdir(exist_ok=True)
text = (
    "// Test simfile for ddr-trainer's loader. The file itself is valid, but loading its\n"
    "// folder should fail because the file's name doesn't match the folder's.\n" + GENERATED
)
(folder / "other name.sm").write_text(text + VALID.format(title="other name"), encoding="utf-8")